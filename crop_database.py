"""
AGRI-X AI — Crop database (38 crops grown across India).

Each crop lists what it needs (growing-season temperature, water, soil pH, soil
groups and textures), what it typically yields and what it typically earns.

Prices
  • MSP (government Minimum Support Price): Kharif 2026-27 and Rabi marketing
    season 2027-28 as announced by the Government of India; sugarcane uses the
    2026-27 FRP (₹365/qtl).
  • Market ranges (₹/quintal) for crops without MSP are typical wholesale mandi
    ranges and swing a lot season to season — treat them as rough guides.
Yields are typical Indian farm yields (t/acre): "avg" for ordinary management,
"good" for well-managed irrigated fields.
"""

SOIL_TEXTURES = ["Sandy", "Sandy Loam", "Loam", "Silt Loam", "Sandy Clay Loam", "Clay Loam", "Clay"]


def _crop(icon, category, seasons, days, temp, water, ph, groups, textures, yld, price, msp, cost,
          water_need, rotation, companion, npk, humidity=(50, 75), t_base=10.0, note=""):
    t_min, opt_lo, opt_hi, t_max = temp
    months = max(1.0, days / 30.0)
    avg_y, good_y = yld
    p_lo, p_hi = price
    mid_price = (p_lo + p_hi) / 2
    if msp:
        mid_price = max(mid_price, msp)
    return {
        # new, richer fields
        "icon": icon, "category": category, "season": seasons, "duration_days": days,
        "temp_range": temp, "water_mm": water, "ph_range": ph, "soil_groups": groups, "textures": textures,
        "water_need": water_need, "note": note,
        # fields used across the app (yield predictor, insights, reports)
        "temp_min": t_min, "temp_max": t_max, "optimal_temp": (opt_lo, opt_hi),
        "humidity_min": humidity[0] - 10, "humidity_max": humidity[1] + 10, "optimal_humidity": humidity,
        "rainfall_min": water[0], "rainfall_max": water[1],
        "optimal_monthly_rain": (round(water[0] / months), round(water[1] / months)),
        "soil": list(textures) + list(groups),
        "yield_per_acre": avg_y, "yield_max_per_acre": good_y,
        "price_min_qt": p_lo, "price_max_qt": p_hi, "price_per_tonne": int(mid_price * 10),
        "msp": msp, "cost_per_acre": cost, "harvest_months": round(months, 1),
        "t_base": t_base, "gdd_target": int(days * max(4, (opt_lo + opt_hi) / 2 - t_base)),
        "npk_demand": npk, "rotation_crops": rotation, "companion_crops": companion,
    }


